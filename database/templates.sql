create table templates
(
    template_id   bigint generated by default as identity
        primary key,
    content       varchar(255),
    template_name varchar(255) not null,
    subject       varchar(255),
    template_type varchar(255) not null
        constraint templates_template_type_check
            check ((template_type)::text = ANY ((ARRAY ['EMAIL'::character varying, 'SMS'::character varying])::text[]))
);

alter table templates
    owner to postgres;

