create table traitements
(
    id               bigint generated by default as identity
        primary key,
    user_id          varchar(255) not null,
    type             varchar(255) not null,
    rubrique         varchar(255) not null,
    medicament       varchar(255),
    precision_text   varchar(255),
    frequence        varchar(255) not null,
    frequence_semaines integer,
    puissance_mg     double precision,
    nombre_comprimes double precision,
    score            double precision,
    reminder_enabled boolean,
    reminder_hour    integer,
    reminder_minute  integer,
    created_at       timestamp(6) not null,
    updated_at       timestamp(6) not null,
    constraint uk_traitements_user_type unique (user_id, type)
);

alter table traitements
    owner to postgres;
