create table account
(
    id                 bigint generated by default as identity
        primary key,
    created_at         timestamp(6) with time zone,
    created_by         bigint,
    updated_at         timestamp(6) with time zone,
    updated_by         bigint,
    account_non_locked boolean,
    email              varchar(255) not null
        constraint ukq0uja26qgu1atulenwup9rxyr
            unique,
    enabled            boolean      not null,
    failed_attempts    integer,
    first_name         varchar(128),
    is_first_login     boolean      not null,
    last_name          varchar(128),
    locked_at          timestamp(6) with time zone,
    login              varchar(255) not null
        constraint uk5vxwyorsr92jce3ore6h93k6q
            unique,
    password           varchar(255) not null,
    phone_number       varchar(255),
    status             varchar(16)  not null
        constraint account_status_check
            check ((status)::text = ANY
                   ((ARRAY ['ENABLED'::character varying, 'DISABLED'::character varying, 'PENDING_APPROVAL'::character varying])::text[])),
    user_type          varchar(32)  not null
        constraint account_user_type_check
            check ((user_type)::text = ANY
                   ((ARRAY ['INTERNAL'::character varying, 'CLIENT'::character varying, 'PARTNER'::character varying, 'COMMITTEE'::character varying])::text[])),
    username           varchar(255) not null
        constraint ukgex1lmaqpg0ir5g1f5eftyaa1
            unique,
    role_id            bigint       not null
        constraint fkd4vb66o896tay3yy52oqxr9w0
            references role
);

