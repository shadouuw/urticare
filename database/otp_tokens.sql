create table otp_tokens
(
    id             bigint generated by default as identity
        primary key,
    attempts       integer,
    created_at     timestamp(6),
    expiry_date    timestamp(6) not null,
    identifier     varchar(255) not null,
    token          varchar(255) not null,
    type           varchar(255) not null
        constraint otp_tokens_type_check
            check ((type)::text = ANY
                   ((ARRAY ['EMAIL'::character varying, 'SMS'::character varying, 'LOGIN'::character varying, 'REGISTRATION'::character varying, 'PASSWORD_RESET'::character varying])::text[])),
    used           boolean      not null,
    otp_session_fk bigint
        constraint fkoyy4fwx60mnjrxuwery87x1ud
            references otp_auth_sessions
);

